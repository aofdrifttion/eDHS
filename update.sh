#!/usr/bin/env bash
# ==============================================================================
#              eDebtor Hospital System (eDHS) - ระบบอัปเดตอัตโนมัติ (Linux)
# ==============================================================================

set -e

# ย้ายไปยังไดเรกทอรีที่สคริปต์นี้อยู่
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "=============================================================================="
echo "             eDebtor Hospital System (eDHS) - ระบบอัปเดตอัตโนมัติ"
echo "=============================================================================="
echo ""

# 1. ตรวจสอบและดึงไฟล์ล่าสุดจาก GitHub
echo "[1/3] กำลังตรวจสอบและดึงไฟล์อัปเดตจาก GitHub..."
if command -v git >/dev/null 2>&1; then
    git pull origin master || echo "[คำเตือน] git pull ไม่สำเร็จ จะดำเนินการอัปเดตจากไฟล์ในเครื่องต่อ..."
else
    echo "[แจ้งเตือน] ไม่พบคำสั่ง git ข้ามขั้นตอน git pull และใช้ไฟล์อัปเดตในเครื่อง..."
fi

echo ""

# 2. ตรวจสอบสภาพแวดล้อม PHP
echo "[2/3] กำลังตรวจสอบสภาพแวดล้อม PHP..."
if ! command -v php >/dev/null 2>&1; then
    echo "[ข้อผิดพลาด] ไม่พบโปรแกรม php ในระบบ กรุณาติดตั้ง php-cli (เช่น sudo apt install php-cli)"
    exit 1
fi
echo "[สำเร็จ] พบ PHP ที่: $(which php)"

echo ""

# 3. รันตัวประมวลผลอัปเดตแกนกลาง
echo "[3/3] กำลังดำเนินการติดตั้งไฟล์แพตช์และอัปเดตระบบ..."
echo "------------------------------------------------------------------------------"
php update_core.php --cli
echo "------------------------------------------------------------------------------"

# 4. คืนค่าสิทธิ์ไฟล์สำหรับ Web Server (Apache/Nginx) หากรันด้วย root
if [ "$EUID" -eq 0 ]; then
    echo "[*] กำลังปรับสิทธิ์ไฟล์ให้ Web Server (www-data)..."
    if id "www-data" >/dev/null 2>&1; then
        chown -R www-data:www-data "$SCRIPT_DIR"
        chmod -R 755 "$SCRIPT_DIR"
    fi
fi

echo ""
echo "=============================================================================="
echo " การอัปเดตเสร็จสมบูรณ์เรียบร้อยแล้ว"
echo "=============================================================================="
